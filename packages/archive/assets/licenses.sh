#!/usr/bin/env bash
# License bookkeeping for the archive toolset, sourced by the build scripts (bash 3.2 compatible). Writes, inside
# $STAGE, the layout scripts/verify-licenses.sh checks plus the GPL corresponding-source pointer:
#   LICENSES/<component>/   the component's license files, copied from its verified source tarball (or, for a
#                           library rpm takes from the build image / Homebrew, from that package)
#   LICENSES/MANIFEST.tsv   "<binary><TAB><component>", one line per component a binary contains
#   LICENSES/SOURCES.txt    one "[component]" block per component: version, license, source URL, sha256
# Needs constants.sh sourced first.

LICENSES_REPO="https://github.com/electron-userland/electron-builder-binaries"

# sources_header: starts LICENSES/SOURCES.txt (once)
sources_header() {
    local f="$STAGE/LICENSES/SOURCES.txt" rev
    [ -f "$f" ] && return 0
    mkdir -p "$STAGE/LICENSES"
    rev="${GITHUB_SHA:-$(git -C "$ARCHIVE_ASSETS" rev-parse HEAD 2>/dev/null || echo unknown)}"
    {
        echo "Corresponding source of the binaries in this bundle"
        echo "==================================================="
        echo ""
        echo "Every component below was built from the upstream release named here, unmodified unless patches are"
        echo "listed, after checking the sha256 (and, where upstream signs the release, the OpenPGP signature)."
        echo "The build scripts are packages/archive/assets/ in $LICENSES_REPO"
        echo "at commit $rev."
        echo "LICENSES/MANIFEST.tsv maps every bundled binary to the components it contains; each component's"
        echo "license texts are in LICENSES/<component>/."
        echo ""
    } >"$f"
}

# add_source_block <component> <version> <license> <source> <sha256 or ""> <note>
add_source_block() {
    sources_header
    {
        echo "[$1]"
        echo "  version:  $2"
        echo "  license:  $3"
        echo "  source:   $4"
        if [ -n "$5" ]; then echo "  sha256:   $5"; fi
        echo "  licenses: LICENSES/$1/ ($(cd "$STAGE/LICENSES/$1" && ls | tr '\n' ' ' | sed 's/ $//'))"
        echo "  notes:    $6"
        echo ""
    } >>"$STAGE/LICENSES/SOURCES.txt"
}

# add_component <COMPONENT> <component dir> <source dir> <note>: license files from the source tree (every file in
# <COMPONENT>_LICENSE_FILES must exist and be non-empty) and the SOURCES.txt block of a component built here
add_component() {
    local c="$1" dir="$2" src="$3" note="$4" dest f sig keys urls
    dest="$STAGE/LICENSES/$dir"
    mkdir -p "$dest"
    for f in $(component_var "$c" LICENSE_FILES); do
        [ -s "$src/$f" ] || die "$c: license file $f is missing or empty in $(basename "$src")"
        cp "$src/$f" "$dest/$f"
    done
    sig=$(component_var "$c" SIG)
    keys=$(component_var "$c" KEYS)
    urls=$(component_var "$c" URLS)
    if [ -n "$sig" ]; then
        note="$note OpenPGP signature ($(basename "${urls%% *}")$sig) verified against key(s) $keys."
    fi
    add_source_block "$dir" "$(component_var "$c" VERSION)" "$(component_var "$c" LICENSE)" "${urls%% *}" \
        "$(component_var "$c" SHA256)" "$note"
    echo "  📄 LICENSES/$dir: $(cd "$dest" && ls | tr '\n' ' ')"
}

# add_binaries <component dir> <bundle-relative path...>
add_binaries() {
    local dir="$1" p
    shift
    for p in "$@"; do
        printf '%s\t%s\n' "$p" "$dir" >>"$STAGE/LICENSES/MANIFEST.tsv"
    done
}

# finish_manifest: header, sorted and de-duplicated
finish_manifest() {
    local m="$STAGE/LICENSES/MANIFEST.tsv"
    {
        echo "# Bundled binary<TAB>component (LICENSES/<component>/). Generated by packages/archive/assets/; checked by"
        echo "# scripts/verify-licenses.sh. Where each component's source is: LICENSES/SOURCES.txt"
        grep -v '^#' "$m" | sort -u
    } >"$m.tmp"
    mv "$m.tmp" "$m"
}
